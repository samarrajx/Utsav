/**
 * dom.js - Safe DOM element construction and inline SVG icons
 *
 * Enforces security invariant: NEVER uses innerHTML with user or model text.
 * All text is set via textContent or TextNodes.
 */

/**
 * Create a DOM element with attributes, event listeners, and children safely.
 *
 * @param {string} tag
 * @param {Object} [props={}]
 * @param {Array<Node|string>|Node|string} [children=[]]
 * @returns {HTMLElement}
 */
export function el(tag, props = {}, children = []) {
  const element = document.createElement(tag);

  for (const [key, val] of Object.entries(props)) {
    if (val === undefined || val === null) continue;

    if (key.startsWith("on") && typeof val === "function") {
      const eventName = key.substring(2).toLowerCase();
      element.addEventListener(eventName, val);
    } else if (key === "className" || key === "class") {
      element.className = String(val);
    } else if (key === "dataset" && typeof val === "object") {
      for (const [dKey, dVal] of Object.entries(val)) {
        element.dataset[dKey] = String(dVal);
      }
    } else if (key === "style" && typeof val === "object") {
      Object.assign(element.style, val);
    } else if (key === "disabled" || key === "checked" || key === "selected") {
      if (val) {
        element.setAttribute(key, "");
        element[key] = true;
      } else {
        element.removeAttribute(key);
        element[key] = false;
      }
    } else {
      element.setAttribute(key, String(val));
    }
  }

  const childArray = Array.isArray(children) ? children : [children];
  for (const child of childArray) {
    if (child === undefined || child === null || child === false) continue;
    if (typeof child === "string" || typeof child === "number") {
      element.appendChild(document.createTextNode(String(child)));
    } else if (child instanceof Node) {
      element.appendChild(child);
    }
  }

  return element;
}

/**
 * Remove all children from a DOM container element
 * @param {HTMLElement} parent
 */
export function clearElement(parent) {
  if (!parent) return;
  while (parent.firstChild) {
    parent.removeChild(parent.firstChild);
  }
}

